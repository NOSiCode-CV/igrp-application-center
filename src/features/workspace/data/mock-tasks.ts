import type { Task } from '../types'

function daysFromNow(n: number): Date {
  const d = new Date()
  d.setDate(d.getDate() + n)
  d.setHours(17, 0, 0, 0)
  return d
}

function daysAgo(n: number): Date {
  return daysFromNow(-n)
}

